const chunk = (arr, n) => { const out = Array.from({ length: n }, () => []); arr.forEach((u, i) => out[Math.floor((i * n) / arr.length)].push(u)); return out; };

function mathMonth(grade, month) {
  if (grade === '고3') {
    return { units: MATH_G3[month], focus: month >= 3 && month <= 11 ? '기출 분석 → 실전 연습 → 오답 유형 정리' : MATH_FOCUS.next,
      tip: month >= 9 && month <= 11 ? '컨디션 관리가 가장 중요한 시기예요. 잠과 식사를 챙겨 주세요.' : MATH_TIP.unit };
  }
  const [s1, s2] = MATH[grade];
  const m1 = chunk(s1, 4), m2 = chunk(s2, 3);
  if (month >= 3 && month <= 6) return { units: m1[month - 3], focus: MATH_FOCUS.unit, tip: UNIT_TIPS[month] };
  if (month === 7) return { units: ['1학기 총정리'], focus: MATH_FOCUS.review, tip: MATH_TIP.review };
  if (month === 8) return { units: s2.slice(0, 2).map((u) => `${u} 예습`), focus: MATH_FOCUS.preview, tip: MATH_TIP.preview };
  if (month >= 9 && month <= 11) return { units: m2[month - 9], focus: MATH_FOCUS.unit, tip: UNIT_TIPS[month] };
  if (month === 12) return { units: ['2학기 총정리'], focus: MATH_FOCUS.review2, tip: MATH_TIP.review2 };
  // 1~2월: 다음 학년 1학기 앞부분/뒷부분 예습
  const nx = NEXT[grade];
  if (!MATH[nx]) return { units: [month === 1 ? '예비 고3: 대수 총복습' : '예비 고3: 미적분I 총복습'], focus: '수능 공통과목 개념을 한 번에 다시 정리', tip: MATH_TIP.next };
  const [a, b] = chunk(MATH[nx][0], 2);
  return { units: (month === 1 ? a : b).map((u) => `${nx} ${u}`), focus: MATH_FOCUS.next, tip: MATH_TIP.next };
}

